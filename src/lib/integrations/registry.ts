const BY_KEY: Record<string, ProviderDescriptor> = Object.fromEntries(
  PROVIDERS.map((p) => [p.key, p]),
)

/**
 * The descriptor for a provider key, or null. A `LIST` can carry rows that are not
 * providers at all (an API client, a webhook receipt); those answer null, never throw.
 */
export function descriptorOf(key: string): ProviderDescriptor | null {
  return BY_KEY[key] ?? null
}

/** The fields the credentials card asks for — empty for every non-PAGE source. */
export function credentialFieldsOf(d: ProviderDescriptor): CredentialField[] {
  return d.credentialSource === 'PAGE' ? d.credentialFields : []
}

/** True when a live connection is possible at all. */
export function isApplicable(d: ProviderDescriptor): boolean {
  return d.applicability !== 'NOT_APPLICABLE'
}

/**
 * The capabilities that have a real implementation in this repo today — not the ones
 * the provider offers. Most rows have none: a credential in SSM does not make a DAT
 * post exist, and a page that hid *Run stub* on the strength of a stored key would be
 * claiming work nothing can do. The default is `['validate']` where a live check is
 * wired and nothing otherwise.
 */
export function liveCapabilitiesOf(d: ProviderDescriptor): Capability[] {
  if (d.liveCapabilities) return d.liveCapabilities
  return d.validateHow.liveCheck ? ['validate'] : []
}

/**
 * What this provider still needs before it can be live — the exact list the page's
 * banner and the build log print.
 *
 * PAGE: the labels of the required fields with no stored mask entry. STACK: the secret
 * names the stack does not hold; the browser never knows that, so an omitted
 * `stackPresent` answers `[]` rather than guessing every name is missing.
 */
export function missingCredentials(
  d: ProviderDescriptor,
  mask?: CredentialMaskEntry[] | null,
  stackPresent?: Record<string, boolean>,
): string[] {
  if (d.credentialSource === 'PAGE') {
    const held = new Set((mask ?? []).map((entry) => entry.key))
    return d.credentialFields.filter((f) => !f.optional && !held.has(f.key)).map((f) => f.label)
  }
  if (d.credentialSource === 'STACK') {
    if (!stackPresent) return []
    return d.stackSecretNames.filter((name) => stackPresent[name] !== true)
  }
  return []
}
